  function sortFamily(arr) {
    if (sortMode === 'default' || !arr.length) return arr;
    const copy = [...arr];
    const pOrder = { verb:0, partic:1, masdar:2, noun:3, plural:4, other:5 };
    if (sortMode === 'alpha') copy.sort((a,b) => a.word.localeCompare(b.word, 'fa'));
    else if (sortMode === 'length') copy.sort((a,b) => a.word.replace(/[\u064B-\u065F\u0670]/g,'').length - b.word.replace(/[\u064B-\u065F\u0670]/g,'').length || a.word.localeCompare(b.word, 'fa'));
    else if (sortMode === 'pattern') copy.sort((a,b) => {
      const pa = pOrder[patternFamily(a.pattern)] ?? 5;
      const pb = pOrder[patternFamily(b.pattern)] ?? 5;
      return pa - pb || a.word.localeCompare(b.word, 'fa');
    });
    return copy;
  }

