  function tryPattern(pat, word) {
    if (pat.length !== word.length) return null;
    let f = null, a = null, l = null;
    for (let i = 0; i < pat.length; i++) {
      let p = pat[i], w = word[i];
      if (p === 'ف') { if (f === null) f = w; else if (f !== w) return null; }
      else if (p === 'ع') { if (a === null) a = w; else if (a !== w) return null; }
      else if (p === 'ل') { if (l === null) l = w; else if (l !== w) return null; }
      else if (p !== w) return null;
    }
    return (f && a && l) ? f + a + l : null;
  }

