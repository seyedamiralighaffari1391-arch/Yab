  function getSuggestions(str) {
    if (!str) return [];
    const n = normalize(str);
    const seen = new Set();
    const result = [];
    for (const h of history) {
      if (result.length >= 8) break;
      const nh = normalize(h);
      if ((nh.startsWith(n) || nh.includes(n)) && !seen.has(h)) { seen.add(h); result.push({ word: h, root: null }); }
    }
    for (const [w, r] of Object.entries(customDB)) {
      if (result.length >= 8) break;
      const nw = normalize(w);
      if (nw.startsWith(n) && !seen.has(w)) { seen.add(w); result.push({ word: w, root: r }); }
    }
    for (const r of recentRoots) {
      if (result.length >= 8) break;
      if (r.startsWith(n) && !seen.has(r)) { seen.add(r); result.push({ word: r, root: null }); }
    }
    return result;
  }

