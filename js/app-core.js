  function substituteRoot(pattern, root) {
    const [f, a, l] = root.split('');
    let out = '';
    for (const ch of pattern) {
      if (ch === 'ف') out += f;
      else if (ch === 'ع') out += a;
      else if (ch === 'ل') out += l;
      else out += ch;
    }
    return out;
  }

