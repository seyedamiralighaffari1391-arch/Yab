  // فاصله لِوِنشتاین — برای پیدا کردن کلمات مشابه
  function levenshtein(a, b) {
    const m = a.length, n = b.length;
    if (!m) return n; if (!n) return m;
    let prev = new Array(n+1);
    for (let j = 0; j <= n; j++) prev[j] = j;
    for (let i = 1; i <= m; i++) {
      const cur = new Array(n+1); cur[0] = i;
      for (let j = 1; j <= n; j++) {
        const cost = a[i-1] === b[j-1] ? 0 : 1;
        cur[j] = Math.min(prev[j] + 1, cur[j-1] + 1, prev[j-1] + cost);
      }
      prev = cur;
    }
    return prev[n];
  }

  function findSimilarWords(word, limit = 6) {
    const n = normalize(word);
    if (!n) return [];
    const candidates = new Set();
    for (const h of history) if (h && normalize(h) !== n) candidates.add(h);
    for (const w of Object.keys(customDB)) if (w && normalize(w) !== n) candidates.add(w);
    const arr = [...candidates].map(c => ({ word: c, dist: levenshtein(n, normalize(c)) }));
    const maxD = Math.max(2, Math.floor(n.length / 2));
    arr.sort((a, b) => a.dist - b.dist);
    const result = [];
    for (const x of arr) { if (x.dist > maxD) break; result.push(x.word); if (result.length >= limit) break; }
    return result;
  }

